    materialized = 'incremental',
    schema = 'CORE',
    unique_key = 'TRANSACTION_ID',
    incremental_strategy = 'merge'
) }}

SELECT
   s.TRANSACTION_ID,
   s.TRANSACTION_DATE,
   TO_NUMBER(TO_CHAR(s.TRANSACTION_DATE, 'YYYYMMDD')) AS DATE_KEY,
   s.TRANSACTION_TYPE,
   s.AMOUNT,
   s.RUNNING_BALANCE,
   COALESCE(NULLIF(TRIM(s.MERCHANT_NAME), ''), 'Unknown') AS MERCHANT_NAME,
   s.CURRENCY,
   s.TRANSACTION_STATUS,
   CONCAT(
    UPPER(TRIM(s.PAYMENT_CHANNEL)),
    '_',
    UPPER(TRIM(s.PAYMENT_METHOD))
) AS PAYMENT_KEY,
   s.ACCOUNT_ID,
   s.BRANCH_ID,
   CASE WHEN s.COMPLAINT_ID IS NULL THEN 'N/A' ELSE s.COMPLAINT_ID END AS COMPLAINT_ID,
   CASE WHEN s.CREDIT_CARD_ID IS NULL THEN 'N/A' ELSE s.CREDIT_CARD_ID END AS CREDIT_CARD_ID,
   s.CUSTOMER_ID,
   CASE WHEN s.LOAN_ID IS NULL THEN 'N/A' ELSE s.LOAN_ID END AS LOAN_ID,
   s.IS_FLAGGED_FRAUD
FROM {{ ref ('stg_banking_data') }} AS s 
WHERE s.TRANSACTION_ID IS NOT NULL

QUALIFY ROW_NUMBER() OVER (PARTITION BY s.TRANSACTION_ID ORDER BY s.TRANSACTION_ID) = 1